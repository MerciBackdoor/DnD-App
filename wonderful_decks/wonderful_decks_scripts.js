function initializeDeck(deckName) {
    currentDecksState[deckName] = JSON.parse(JSON.stringify(decksData[deckName]));
    updateStatusText();
    saveStateToStorage(); 
}

function resetAll() {
    Object.keys(decksData).forEach(initializeDeck);
    document.getElementById('cards-display').innerHTML = '';
    saveStateToStorage(); 
}

function updateStatusText() {
    const selectedDeck = document.getElementById('deck-select').value;
    const infoSpan = document.getElementById('deck-info');
    const countInput = document.getElementById('card-count');
    
    if (selectedDeck === 'wild') {
        infoSpan.textContent = 'Осталось карт в колоде: ∞ (Карты мгновенно возвращаются)';
        countInput.max = 100;
    } else {
        const count = currentDecksState[selectedDeck] ? currentDecksState[selectedDeck].length : 0;
        infoSpan.textContent = `Осталось карт в колоде: ${count} / ${decksData[selectedDeck].length}`;
        countInput.max = selectedDeck.includes('many') ? 10 : count; 
    }
}

function drawCards() {
    const deckName = document.getElementById('deck-select').value;
    const countInput = document.getElementById('card-count');
    let requestedCount = parseInt(countInput.value) || 1;
    const display = document.getElementById('cards-display');

    if (requestedCount < 1) requestedCount = 1;
    display.innerHTML = ''; 

    let deckPool = currentDecksState[deckName];

    if (deckName !== 'wild' && (!deckPool || deckPool.length === 0)) {
        display.innerHTML = `<div style="color: var(--danger-color); font-weight: bold; grid-column: 1/-1; text-align: center;">Колода пуста! Требуется перетасовать колоду.</div>`;
        return;
    }

    if ((deckName === 'miscellany' || deckName === 'illusions') && requestedCount > deckPool.length) {
        requestedCount = deckPool.length;
    }

    for (let i = 0; i < requestedCount; i++) {
        if (deckPool.length === 0) break;
        
        let randomIndex = Math.floor(Math.random() * deckPool.length);
        let card;

        if (deckName === 'miscellany' || deckName === 'illusions') {
            card = deckPool.splice(randomIndex, 1)[0];
        } else if (deckName === 'many_things' || deckName === 'many_more') {
            card = deckPool[randomIndex];
            if (card.name === 'Дурак' || card.name === 'Шут' || card.name === 'Джокер') {
                deckPool.splice(randomIndex, 1);
            }
        } else if (deckName === 'wonder') {
            card = deckPool[randomIndex];
            if (card.name === 'Тайна') {
                deckPool.splice(randomIndex, 1);
            }
        } else {
            card = deckPool[randomIndex];
        }

        createCardElement(card, deckName);
    }

    updateStatusText();
    saveStateToStorage(); // Сохраняем и остатки колод, и новые отрисованные карты
}

function createCardElement(card, deckName) {
    const display = document.getElementById('cards-display');
    const cardDiv = document.createElement('div');
    cardDiv.className = 'card';

    let suitClass = 'suit-gold';
    if (card.suit === '♥' || card.suit === '♦') suitClass = 'suit-red';
    if (card.suit === '♣' || card.suit === '♠') suitClass = 'suit-black';

    const cardDisplayName = card.name ? card.name : card.val;

    cardDiv.innerHTML = `
        <div class="card-header">
            <span>${cardDisplayName}</span>
            <span class="${suitClass}">${card.suit}</span>
        </div>
        <div class="card-body">
            ${card.text}
        </div>
        <div class="card-footer">
            ${cardDisplayName} ${card.suit}
        </div>
    `;

    display.appendChild(cardDiv);
}

