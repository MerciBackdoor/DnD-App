const generateBtn = document.getElementById('generate-btn');
    const lootDisplay = document.getElementById('loot-display');
    const trinketText = document.getElementById('trinket-text');

    const coinElements = {
        gp: document.getElementById('coin-gp'),
        sp: document.getElementById('coin-sp'),
        cp: document.getElementById('coin-cp')
    };

    if (generateBtn && lootTable.length > 0) {
        generateBtn.disabled = false;
    }

    // Восстанавливаем сохраненный лут при открытии приложения
    loadSavedLoot();

    generateBtn.addEventListener('click', generateLoot);

    function generateLoot() {
        if (lootTable.length === 0) return;

        // 1. Выбор случайной безделушки
        const randomIndex = Math.floor(Math.random() * lootTable.length);
        const selectedTrinket = lootTable[randomIndex];

        // 2. Расчет монет
        let totalCopper = Math.floor(Math.random() * (980 - 3 + 1)) + 3;
        
        let gp = 0;
        let sp = 0;
        let cp = 0;

        const coinRoll = Math.random();

        if (coinRoll < 0.15 && totalCopper >= 100) {
            gp = Math.floor(totalCopper / 100);
            let remainder = totalCopper % 100;
            sp = Math.floor(remainder / 10);
            cp = remainder % 10;
        } else if (coinRoll < 0.65) {
            sp = Math.floor(totalCopper / 10);
            cp = totalCopper % 10;
        } else {
            cp = totalCopper;
        }

        // Конвертация меди, если её больше 55
        if (cp > 55) {
            let extraSilver = Math.floor(cp / 10);
            sp += extraSilver;
            cp = cp % 10;
        }

        // Отображаем и сохраняем
        displayLoot(selectedTrinket, gp, sp, cp);
        saveLoot(selectedTrinket, gp, sp, cp);
    }

    // Универсальная функция для вывода данных на экран
    function displayLoot(trinket, gp, sp, cp) {
        trinketText.textContent = trinket;
        updateCoinDisplay('gp', gp);
        updateCoinDisplay('sp', sp);
        updateCoinDisplay('cp', cp);
        lootDisplay.classList.remove('hidden');
    }

    function updateCoinDisplay(type, amount) {
        const el = coinElements[type];
        if (!el) return;
        
        const countEl = el.querySelector('.coin-count');
        
        if (amount > 0) {
            if (countEl) {
                countEl.textContent = amount;
            }
            el.classList.remove('hidden');
        } else {
            el.classList.add('hidden');
        }
    }

    // Сохранение в LocalStorage
    function saveLoot(trinket, gp, sp, cp) {
        const lootState = { trinket, gp, sp, cp };
        localStorage.setItem('dnd_last_loot', JSON.stringify(lootState));
    }

    // Загрузка из LocalStorage
    function loadSavedLoot() {
        const savedData = localStorage.getItem('dnd_last_loot');
        if (savedData) {
            try {
                const { trinket, gp, sp, cp } = JSON.parse(savedData);
                displayLoot(trinket, gp, sp, cp);
            } catch (e) {
                console.error("Ошибка чтения сохраненного лута", e);
            }
        }
    }
