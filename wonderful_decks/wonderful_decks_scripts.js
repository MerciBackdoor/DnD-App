let currentDecksState = {};

// --- СВЕРХНАДЕЖНОЕ СОХРАНЕНИЕ ВСЕГО СОСТОЯНИЯ ---
function saveStateToStorage() {
    const fullState = {
        decksState: currentDecksState,
        displayHtml: document.getElementById('cards-display').innerHTML,
        selectedDeck: document.getElementById('deck-select').value,
        cardCount: document.getElementById('card-count').value
    };
    localStorage.setItem('wonderful_decks_complete_state', JSON.stringify(fullState));
}

function loadStateFromStorage() {
    const saved = localStorage.getItem('wonderful_decks_complete_state');
    if (saved) {
        try {
            const fullState = JSON.parse(saved);
            currentDecksState = fullState.decksState;
            
            // Восстанавливаем выбранные селекты и инпуты
            document.getElementById('deck-select').value = fullState.selectedDeck || 'miscellany';
            document.getElementById('card-count').value = fullState.cardCount || 1;
            
            // Возвращаем вытянутые на экран карты
            document.getElementById('cards-display').innerHTML = fullState.displayHtml || '';
            return true;
        } catch (e) {
            console.error("Ошибка чтения полной сессии из localStorage", e);
            return false;
        }
    }
    return false;
}
